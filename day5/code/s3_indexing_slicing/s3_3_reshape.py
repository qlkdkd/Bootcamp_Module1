import numpy as np 


b = np.arange(1, 13).reshape(3, 4) # 1~12 를 3 줄 4 칸으로 
print(b) 


# 칸 0 1 2 3 

# 줄 0 [[ 1 2 3 4] 
# 줄 1 [ 5 6 7 8] 
# 줄 2 [ 9 10 11 12]] 

print(b[1, 2]) # 7 ← 1 번 줄, 2 번 칸
print(b[0]) # [1 2 3 4] ← 0 번 줄 통째로 
print(b[:, 1]) # [ 2 6 10] ← 모든 줄의 1 번 칸 (세로 한 줄) 
print(b[0:2, 1:3]) # 0~1 번 줄, 1~2 번 칸으로 된 네모 영역 
# [[2 3] 
# [6 7]] 
